#!/usr/bin/env node
/* gen-blocklist.js — build docs/blocklist-seed.sql for the username moderator.
 *
 * We do NOT author slurs. This pulls the community-maintained LDNOOBW dataset
 * (List of Dirty, Naughty, Obscene and Otherwise Bad Words) for the languages the
 * site cares about, and emits RAW terms that Supabase normalizes at load time via
 * public.pjcc_normalize() — so the list and the live check can never drift.
 *
 *   Run:   npm run gen:blocklist
 *   Then:  paste the produced docs/blocklist-seed.sql into Supabase → SQL Editor
 *          (AFTER docs/username-moderation-setup.sql).
 *
 * The seed file is .gitignored on purpose — a slur dump doesn't belong in the repo.
 * Re-run any time to refresh from upstream. Requires network + Node 18+ (global fetch).
 */
'use strict';
const fs = require('fs');
const path = require('path');

// English · Spanish · European · Indian (Hindi) · Japanese · Korean, plus the
// other widely-abused scripts LDNOOBW ships. Missing files are skipped cleanly.
const LANGS = ['en', 'es', 'fr', 'de', 'it', 'pt', 'nl', 'sv', 'no', 'da', 'fi',
               'pl', 'cs', 'hu', 'tr', 'ru', 'hi', 'ja', 'ko', 'ar', 'th', 'fa', 'tl', 'zh'];
const BASE = 'https://raw.githubusercontent.com/LDNOOBW/List-of-Dirty-Naughty-Obscene-and-Otherwise-Bad-Words/master/';
const OUT = path.join(__dirname, '..', 'docs', 'blocklist-seed.sql');
const CHUNK = 400;   // VALUES rows per INSERT — keeps each statement editor-friendly

const esc = s => s.replace(/'/g, "''");

(async () => {
  const out = [
    '-- GENERATED by tests/gen-blocklist.js — do not edit by hand, do not commit.',
    '-- Source: LDNOOBW (List of Dirty, Naughty, Obscene and Otherwise Bad Words).',
    '-- Load AFTER docs/username-moderation-setup.sql. Terms are normalized in-DB by',
    '-- public.pjcc_normalize(); rows under 3 normalized chars are dropped as too noisy.',
    ''
  ];
  let grand = 0;
  for (const lang of LANGS) {
    let text;
    try {
      const r = await fetch(BASE + lang);
      if (!r.ok) { console.log(`  skip ${lang} (HTTP ${r.status})`); continue; }
      text = await r.text();
    } catch (e) { console.log(`  skip ${lang} (${e.message})`); continue; }

    const seen = new Set();
    for (const raw of text.split(/\r?\n/)) {
      const t = raw.trim();
      if (!t || t.startsWith('#')) continue;
      if (t.length < 2) continue;                 // 1-char raw entries are noise
      seen.add(t.toLowerCase());
    }
    if (!seen.size) continue;
    const terms = [...seen];
    grand += terms.length;
    out.push(`-- ${lang}: ${terms.length} raw terms`);
    for (let i = 0; i < terms.length; i += CHUNK) {
      const rows = terms.slice(i, i + CHUNK).map(t => `  ('${esc(t)}')`).join(',\n');
      out.push('insert into public.blocked_terms(term)');
      out.push('select n from (values');
      out.push(rows);
      out.push(') v(raw), lateral (select public.pjcc_normalize(v.raw)) x(n)');
      out.push('where length(n) >= 3');
      out.push('on conflict (term) do nothing;');
      out.push('');
    }
    console.log(`  ${lang}: ${terms.length}`);
  }
  fs.writeFileSync(OUT, out.join('\n'));
  console.log(`\nWrote ${path.relative(path.join(__dirname, '..'), OUT)} — ${grand} raw terms across ${LANGS.length} languages.`);
  console.log('Paste it into Supabase SQL Editor after username-moderation-setup.sql.');
})().catch(e => { console.error(e); process.exit(1); });
